async function main() {
  console.log("🌱 بدء إدراج البيانات...\n");

  for (const cat of CATEGORIES) {
    await prisma.category.upsert({
      where: { id: cat.id },
      update: { name: cat.name },
      create: { id: cat.id, name: cat.name, image: null },
    });
    console.log(`✅ قسم: ${cat.name}`);
  }

  for (const p of PRODUCTS) {
    await prisma.product.upsert({
      where: { id: p.id },
      update: {
        name: p.name,
        description: p.desc,
        isNew: true,
        image: null,
        categories: { set: [{ id: p.cat }] },
      },
      create: {
        id: p.id,
        name: p.name,
        description: p.desc,
        image: null,
        isNew: true,
        categories: { connect: [{ id: p.cat }] },
      } as any,
    });
    console.log(`   ✅ ${p.name}`);
  }

  console.log(`\n✨ تم! ${PRODUCTS.length} منتج في ${CATEGORIES.length} أقسام`);
}

main()
  .catch((e) => { console.error("❌", e); process.exit(1); })
  .finally(async () => { await prisma.$disconnect(); });
